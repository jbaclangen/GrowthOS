// Compiles design-system/tokens.json (the single token source, D-009) into src/styles/tokens.css.
// Also checks WCAG contrast for every text/background role pair and fails if any drops below AA.
// Run: npm run tokens          (write)
//      npm run tokens -- --check (verify the committed CSS is current; exit 1 if stale)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../../design-system/tokens.json");
const OUT = resolve(here, "../src/styles/tokens.css");

const tokens = JSON.parse(readFileSync(SRC, "utf8"));

const get = (path) => path.split(".").reduce((node, key) => node?.[key], tokens);
function resolveValue(value) {
  if (typeof value !== "string") return value;
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    const node = get(ref);
    if (!node || node.$value === undefined) throw new Error(`Unresolved token reference {${ref}}`);
    return resolveValue(node.$value);
  });
}
// Leaf tokens under a group, skipping $-prefixed metadata keys.
const leaves = (group) => Object.entries(group).filter(([k, v]) => !k.startsWith("$") && v && v.$value !== undefined);

// ---- Contrast gate --------------------------------------------------------------------------
function luminance(hex) {
  const n = hex.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
const contrast = (a, b) => {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};
// [text role, background role, minimum ratio]
const PAIRS = [
  ["foreground", "background", 4.5],
  ["foreground", "surface", 4.5],
  ["muted", "background", 4.5],
  ["muted", "surface", 4.5],
  ["muted", "surface-muted", 4.5],
  ["accent", "background", 4.5],
  ["accent", "surface", 4.5],
  ["accent-foreground", "accent", 4.5],
  ["accent-soft-foreground", "accent-soft", 4.5],
  ["signal-foreground", "signal", 4.5],
  ["success", "surface", 4.5],
  ["warning", "surface", 4.5],
  ["danger", "surface", 4.5],
  ["success", "success-soft", 4.5],
  ["warning", "warning-soft", 4.5],
  ["danger", "danger-soft", 4.5],
  ["info", "info-soft", 4.5],
  ["focus", "surface", 3],
];

const failures = [];
const report = [];
for (const mode of ["light", "dark"]) {
  const t = Object.fromEntries(leaves(tokens.theme[mode]).map(([k, v]) => [k, resolveValue(v.$value)]));
  for (const [fg, bg, min] of PAIRS) {
    const ratio = contrast(t[fg], t[bg]);
    report.push(`${mode.padEnd(5)} ${fg.padEnd(24)} on ${bg.padEnd(14)} ${ratio.toFixed(2)}:1`);
    if (ratio < min) failures.push(`${mode}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1 (needs ${min}:1)`);
  }
}
if (failures.length) {
  console.error("Contrast check failed:\n  " + failures.join("\n  "));
  process.exit(1);
}

// ---- CSS emit -------------------------------------------------------------------------------
const lines = [];
const push = (s = "") => lines.push(s);
const themeVars = (mode, indent) =>
  leaves(tokens.theme[mode]).map(([k, v]) => `${indent}--${k}: ${resolveValue(v.$value)};`);

push("/* GENERATED by web/scripts/build-tokens.mjs from design-system/tokens.json — do not edit. */");
push("/* Change tokens.json, then run `npm run tokens`. */");
push();
push("/* Static tokens: become Tailwind utilities (bg-cobalt-600, font-display, rounded-lg, ...). */");
push("@theme {");
for (const scale of ["ink", "cobalt", "volt", "green", "amber", "red", "chart"]) {
  for (const [step, v] of leaves(tokens.color[scale])) push(`  --color-${scale}-${step}: ${resolveValue(v.$value)};`);
}
for (const [name, v] of leaves(tokens.color.brand)) push(`  --color-brand-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.font)) push(`  --font-${name}: ${v.$value};`);
push(`  --text-display: ${tokens.fontSize.display.$value};`);
push(`  --text-display--line-height: ${tokens.fontSize.display.lineHeight};`);
for (const [name, v] of leaves(tokens.tracking)) push(`  --tracking-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.radius)) if (name !== "icon") push(`  --radius-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.shadow)) push(`  --shadow-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.motion.easing)) push(`  --ease-${name}: ${v.$value};`);
push("}");
push();
push("/* Motion, width, and layout tokens as plain variables. */");
push(":root {");
for (const [name, v] of leaves(tokens.motion.duration)) push(`  --duration-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.fontWeight)) push(`  --font-weight-${name}: ${v.$value};`);
for (const [name, v] of leaves(tokens.layout)) push(`  --layout-${name}: ${v.$value};`);
push("}");
push();
push("/* Semantic roles. Light by default; dark follows the OS unless data-theme forces a mode. */");
push(":root {");
push("  color-scheme: light;");
lines.push(...themeVars("light", "  "));
push("}");
push("@media (prefers-color-scheme: dark) {");
push('  :root:not([data-theme="light"]) {');
push("    color-scheme: dark;");
lines.push(...themeVars("dark", "    "));
push("  }");
push("}");
push(':root[data-theme="dark"] {');
push("  color-scheme: dark;");
lines.push(...themeVars("dark", "  "));
push("}");
push();
push("/* Semantic roles as Tailwind colours (bg-surface, text-muted, border-border, ...). */");
push("@theme inline {");
for (const [k] of leaves(tokens.theme.light)) push(`  --color-${k}: var(--${k});`);
push("}");
push();

const css = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current.replace(/\r\n/g, "\n") !== css) {
    console.error("src/styles/tokens.css is stale. Run `npm run tokens`.");
    process.exit(1);
  }
  console.log("tokens.css is up to date; contrast checks pass.");
} else {
  writeFileSync(OUT, css);
  console.log(`Wrote ${OUT}\nContrast (all pass):\n  ${report.join("\n  ")}`);
}
